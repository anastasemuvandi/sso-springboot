// Regenerates src/login/i18n.rw.ts: the *base* Keycloak message set for Kinyarwanda.
//
// Keycloak ships no `rw` translation of its base login messages, and Keycloakify's
// withExtraLanguages() needs a complete base set for every extra language. Like the
// reference FreeMarker theme (whose rw bundle only overrides some keys and lets the
// rest fall back to English), the base set is the English one; every GoRSSO string
// that has a Kinyarwanda translation is supplied via withCustomTranslations in
// src/login/i18n.ts and wins over this file.
//
// Run after upgrading keycloakify:  node scripts/gen-rw-base.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const en = readFileSync(
    join(root, "node_modules/keycloakify/src/login/i18n/messages_defaultSet/en.ts"),
    "utf8"
);
const body = en.slice(en.indexOf("const messages"));
writeFileSync(
    join(root, "src/login/i18n.rw.ts"),
    [
        "// GENERATED by scripts/gen-rw-base.mjs from keycloakify's English base set. Do not edit.",
        "// Kinyarwanda base = English fallback; GoRSSO rw strings live in ./i18n.ts.",
        "/* eslint-disable */",
        body
    ].join("\n")
);
console.log("wrote src/login/i18n.rw.ts");
